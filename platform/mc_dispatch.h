// platform/mc_dispatch.h — portable IDispatch::Invoke over CMUSHclientDoc.
//
// On Windows, the alternate scripting languages (VBScript/JScript/PerlScript/
// Python) reach the world object model through MFC's COM automation: the doc is
// an IDispatch whose dispatch map (doc.cpp, the BEGIN_DISPATCH_MAP block, 408
// methods) is walked by IDispatch::Invoke.  COM/IActiveScript do not exist off
// Windows, so this file rebuilds the *method* half of that mechanism portably.
//
// The dispatch map is shared verbatim with the Windows build via
// doc_dispatch_map.inc.  Here it is re-included with macros that register each
// entry into a name -> thunk table.  Each thunk is generated by a template that
// deduces the C++ signature directly from &CMUSHclientDoc::method — no libffi,
// no member-function-pointer-to-void* casts, no hand-decoding of the VTS_* type
// tokens.  Any method whose parameter/return type is not handled becomes a
// compile error naming that type, so the table is provably complete.
//
// VARIANT is the language-neutral boundary (exactly as COM intended): every
// embedded interpreter converts its own values to/from VARIANT at the edge and
// never sees CMUSHclientDoc directly.  See platform/py_engine.cpp for the
// Python side.
//
// Compiled into mushcore (the shared engine, Stage 9) — it needs the real
// CMUSHclientDoc from doc.h.

#pragma once
#if !defined(_WIN32) && defined(MUSHCLIENT_FULL_BUILD)

#include <string>
#include <vector>

class CMUSHclientDoc;
struct VARIANT;

// Return codes from MC_DispatchInvoke.
enum {
  MC_DISP_OK        =  0,   // call succeeded; `result` holds the return value
  MC_DISP_UNKNOWN   = -1,   // no method of that name in the dispatch map
  MC_DISP_BADARGS   = -2,   // argument marshalling failed
};

// Flags for MC_DispatchInvoke's `flags` parameter.
//
// MC_DISP_F_INTROSPECT marks a call the SCRIPT did not write: Python and
// JavaScript coerce a bare method reference to a string by invoking it with no
// arguments (py_engine.cpp Method_str, js_engine.cpp Method_convertToType), so
// that COM-style plugins which write `world.GetPluginID` without parentheses
// keep working.  That is a language coercion, not a call the author made, and
// strict argument checking must not fire on it -- it would turn every
// `str(world.X)` on a method that takes parameters into the placeholder text.
enum {
  MC_DISP_F_INTROSPECT = 1,   // engine-generated 0-arg coercion, not a script call
};

// Invoke a world-API method by automation name.
//
//   doc      — the world document the call targets (the COM `world` object)
//   name     — automation name, e.g. "Send", "GetVariable", "ColourNote"
//   args     — input arguments as VARIANTs (caller owns; not modified)
//   nargs    — number of input arguments
//   result   — receives the return value; VT_EMPTY for void methods.  The
//              caller takes ownership and must release it with MC_VariantClear.
//   outargs  — if non-null, receives a copy of each [out] VARIANT* parameter in
//              declaration order (for the by-ref getters GetTrigger/GetAlias/
//              GetTimer); the caller owns these and must MC_VariantClear them.
//
//   flags    — zero, or MC_DISP_F_INTROSPECT (see above).
//
// Returns one of the MC_DISP_* codes above.
int MC_DispatchInvoke(CMUSHclientDoc* doc, const char* name,
                      const VARIANT* args, int nargs,
                      VARIANT& result, std::vector<VARIANT>* outargs = nullptr,
                      unsigned flags = 0);

// ── Strict argument checking (world option "script_strict_arguments") ───────
//
// Off by default, the substrate zero-fills every parameter a short argument
// list did not supply, so world.SetVariable("x") silently sets "x" to "".  The
// real IDispatch::Invoke the Windows build rides refuses that outright with
// DISP_E_BADPARAMCOUNT -- the dispatch map declares no VTS_VARIANT anywhere, so
// on Windows every declared parameter is required -- and Lua's own binding
// errors too (my_checkstring on a missing argument).  The leniency is this
// port's invention; the option lets a plugin author opt back into parity while
// developing.  ARITY ONLY, never types: the Tcl engine marshals every argument
// as VT_BSTR by design, so a type-strict check would reject all of Tcl.
//
// The check runs AFTER the kArgDefaults padding, so the Lua-parity defaults
// (EnableTrigger's implicit `true`, DatabaseOpen's sqlite flags, …) still
// apply: a slot the caller omitted is only an error when it has no default.
//
// It counts the arguments the caller WROTE, not the padded list, so an
// explicitly-passed nil (VT_EMPTY) is a supplied argument here even though the
// padding above treats it as an unfilled slot.  Those two readings must stay
// apart: turning strict on would otherwise start rejecting
// world.EnableTrigger("t", None), a call the same option leaves working when
// spelled world.EnableTrigger("t").

// How many leading arguments `name` genuinely requires -- its declared arity
// less any trailing slots kArgDefaults supplies.  -1 if there is no such
// method.  This is the "expected" half of the error message.
int MC_DispatchRequiredArgs(const char* name);

// The engines' shared wording for MC_DISP_BADARGS, e.g.
//   "expected at least 2 arguments, got 1"
// The caller prefixes it with its own "world.Foo: " in its native style.
std::string MC_DispatchBadArgsMessage(const char* name, int nargs);

// True if `name` is a known automation method.
bool MC_DispatchHas(const char* name);

// Is `doc` still an OPEN world document?
//
// A VT_DISPATCH return (world.GetWorld / GetWorldById) is a bare
// CMUSHclientDoc* on this platform -- there is no COM, so nothing AddRefs it the
// way pDoc->GetIDispatch(TRUE) does on Windows.  A script that stores the proxy
// ("other = world.GetWorld('Alt')") and uses it after that world is closed would
// otherwise dereference freed memory.  Every engine's invoke path checks this
// first and reports an error to the script instead.
//
// The authority is a registry the document maintains itself, in its constructor
// and destructor -- NOT the App's doc template, because a document is usable
// before the framework registers it (the engines' own world is exactly that).
bool MC_DispatchDocIsLive(CMUSHclientDoc* doc);

// Called by CMUSHclientDoc's constructor / destructor.
void MC_DispatchDocRegister   (CMUSHclientDoc* doc);
void MC_DispatchDocUnregister (CMUSHclientDoc* doc);

// ── Properties (DISP_PROPERTY_NOTIFY / DISP_PROPERTY_EX) ────────────────────
// The dispatch map's member- and accessor-backed properties (world.Trace,
// world.NoteColour, world.LogNotes, …) surface to scripts as readable/writable
// attributes.  (Indexed DISP_PROPERTY_PARAM properties are instead registered as
// plain Get*/Set* methods, reachable through MC_DispatchInvoke.)
bool MC_DispatchHasProperty(const char* name);

// Read property `name` into `result` (caller releases via MC_VariantClear).
// Returns false if there is no such property.
bool MC_DispatchGetProperty(CMUSHclientDoc* doc, const char* name, VARIANT& result);

// Write `value` to property `name` (and run its change handler, if any).
// Returns false if there is no such property.
bool MC_DispatchSetProperty(CMUSHclientDoc* doc, const char* name, const VARIANT& value);

// Deep-free a VARIANT produced by MC_DispatchInvoke (frees an owned BSTR or
// SAFEARRAY).  The stock VariantClear in mfc_ui.h only frees arrays, so the
// dispatch/engine code routes all VARIANT teardown through this.
void MC_VariantClear(VARIANT& v);

// Deep-copy src into dst (dst is cleared first).  Used to snapshot [out] params.
void MC_VariantCopy(VARIANT& dst, const VARIANT& src);

// A VT_DATE VARIANT as Unix seconds.  This is exactly what Lua's pushVariant
// produces (scripting/lua_methods.cpp:142-159), so all six languages agree on
// what GetInfo(301..306), GetLineInfo(9), GetTimerInfo and GetPluginInfo(13/14/22)
// hand back.  Without it the five embedded engines dropped every date to
// nil/None/undefined, because their variant switches had no VT_DATE arm.
long MC_VariantDateToUnix(const VARIANT& v);

#endif // !_WIN32 && MUSHCLIENT_FULL_BUILD
