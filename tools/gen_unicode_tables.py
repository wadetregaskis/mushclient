#!/usr/bin/env python3
"""Generates src/unicode_tables.inc and tests/unicode_grapheme_cases.inc.

The output is committed; this only needs running for a new version of Unicode.
Fetch these from https://www.unicode.org/Public/<version>/ucd/ into one folder:

    EastAsianWidth.txt
    DerivedCoreProperties.txt
    extracted/DerivedGeneralCategory.txt      (flattened into the folder)
    auxiliary/GraphemeBreakProperty.txt       (flattened)
    auxiliary/GraphemeBreakTest.txt           (flattened)
    emoji/emoji-data.txt                      (flattened)

then:

    python tools/gen_unicode_tables.py <folder>

It is data, not a library: the tables are sorted ranges searched by unicode_width.cpp.
"""

import re
import sys
from pathlib import Path

LINE = re.compile(r'^([0-9A-Fa-f]+)(?:\.\.([0-9A-Fa-f]+))?\s*;\s*([^#]*?)\s*(?:#.*)?$')


def read_ranges(path):
    """Yields (first, last, fields) for every data line of a UCD file."""
    for raw in path.read_text(encoding='utf-8').splitlines():
        match = LINE.match(raw.strip())
        if match:
            first = int(match.group(1), 16)
            last = int(match.group(2), 16) if match.group(2) else first
            yield first, last, [f.strip() for f in match.group(3).split(';')]


def merged(ranges):
    """Sorts (first, last, value) and joins neighbours of equal value."""
    out = []
    for first, last, value in sorted(ranges):
        if out and out[-1][1] + 1 == first and out[-1][2] == value:
            out[-1] = (out[-1][0], last, value)
        else:
            out.append((first, last, value))
    return out


def cover(ranges):
    """(first, last) pairs, joined up."""
    out = []
    for first, last in sorted(ranges):
        if out and first <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], last))
        else:
            out.append((first, last))
    return out


def main():
    ucd = Path(sys.argv[1])
    repo = Path(__file__).resolve().parent.parent

    version = ucd.joinpath('EastAsianWidth.txt').read_text(encoding='utf-8').splitlines()[0]
    version = re.search(r'(\d+\.\d+\.\d+)', version).group(1)

    # ----- width

    categories = list(read_ranges(ucd / 'extracted' / 'DerivedGeneralCategory.txt')
                      if (ucd / 'extracted').exists()
                      else read_ranges(ucd / 'DerivedGeneralCategory.txt'))

    emoji_data = list(read_ranges(ucd / 'emoji-data.txt'))
    emoji_presentation = [(a, b) for a, b, f in emoji_data if f[0] == 'Emoji_Presentation']
    pictographic = [(a, b) for a, b, f in emoji_data if f[0] == 'Extended_Pictographic']

    wide = [(a, b) for a, b, f in read_ranges(ucd / 'EastAsianWidth.txt') if f[0] in ('W', 'F')]
    wide += emoji_presentation

    # Zero width: marks that sit on what's before them, and format characters.  A soft
    # hyphen is the classic exception: it has a width where it's displayed.  So do the
    # Prepend format characters, which sit in front of a letter.
    zero = [(a, b) for a, b, f in categories if f[0] in ('Mn', 'Me', 'Cf', 'Cc', 'Zl', 'Zp')]
    # conjoining vowels and final consonants of old Hangul join the syllable's cell pair
    zero += [(0x1160, 0x11FF), (0xD7B0, 0xD7FF)]

    def without(ranges, hole):
        out = []
        for a, b in ranges:
            if a <= hole <= b:
                if a < hole:
                    out.append((a, hole - 1))
                if hole < b:
                    out.append((hole + 1, b))
            else:
                out.append((a, b))
        return out

    zero = without(cover(zero), 0xAD)

    # ----- grapheme clusters

    prop_names = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend',
                  'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT', 'Pictographic']
    props = [(a, b, f[0]) for a, b, f in read_ranges(ucd / 'GraphemeBreakProperty.txt')]
    props += [(a, b, 'Pictographic') for a, b in pictographic]
    props = merged(props)

    # GB9c: conjuncts in Indic scripts
    incb = []
    core = ucd / 'DerivedCoreProperties.txt'
    for a, b, f in read_ranges(core):
        if f[0] == 'InCB':
            incb.append((a, b, f[1]))
    incb = merged(incb)

    def c_ranges(rows):
        return '\n'.join('  { 0x%X, 0x%X },' % row for row in rows)

    def c_props(rows):
        return '\n'.join('  { 0x%X, 0x%X, eGB_%s },' % row for row in rows)

    def c_incb(rows):
        return '\n'.join('  { 0x%X, 0x%X, eInCB_%s },' % row for row in rows)

    out = f'''// unicode_tables.inc -- GENERATED by tools/gen_unicode_tables.py, from Unicode {version}.
// Do not edit: run the script.  All sorted, and none overlapping within a table.

static const char kUnicodeVersion [] = "{version}";

// East Asian Wide and Fullwidth, and everything with emoji presentation: two cells.
static const CodePointRange kWide [] = {{
{c_ranges(cover(wide))}
}};

// Marks, format and control characters: no cells.
static const CodePointRange kZero [] = {{
{c_ranges(zero)}
}};

// UAX #29 Grapheme_Cluster_Break, plus Extended_Pictographic.
static const CodePointProp kGraphemeBreak [] = {{
{c_props(props)}
}};

// Indic_Conjunct_Break, for rule GB9c.
static const CodePointProp kIndicConjunct [] = {{
{c_incb(incb)}
}};
'''
    (repo / 'src' / 'unicode_tables.inc').write_text(out, encoding='ascii', newline='\n')

    # ----- Unicode's own tests, without its 170 KB of commentary

    cases = []
    for raw in (ucd / 'GraphemeBreakTest.txt').read_text(encoding='utf-8').splitlines():
        line = raw.split('#')[0].strip()
        if not line:
            continue
        # a line like: ÷ 0020 × 0308 ÷ 0020 ÷
        tokens = line.split()
        clusters = []
        current = []
        for token in tokens:
            if token == '÷':
                if current:
                    clusters.append(current)
                current = []
            elif token != '×':
                current.append(token)
        cases.append(clusters)

    rows = []
    for clusters in cases:
        rows.append('  "' + '|'.join(' '.join(cluster) for cluster in clusters) + '",')

    test = f'''// unicode_grapheme_cases.inc -- GENERATED by tools/gen_unicode_tables.py from Unicode {version}'s
// GraphemeBreakTest.txt.  Each string is one test: code points in hex, with | where a cluster ends.

static const char * const kGraphemeCases [] = {{
''' + '\n'.join(rows) + '\n};\n'
    (repo / 'tests' / 'unicode_grapheme_cases.inc').write_text(test, encoding='ascii', newline='\n')

    print(f'Unicode {version}: {len(cover(wide))} wide, {len(zero)} zero, '
          f'{len(props)} grapheme ranges, {len(incb)} conjunct ranges, {len(cases)} test cases')


if __name__ == '__main__':
    main()
